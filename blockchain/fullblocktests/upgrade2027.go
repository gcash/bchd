const (
	// seamAnchorBits are the bits of the ASERT anchor of the seam chain.
	// They are below the proof of work limit so that the 60-tick target,
	// ten times as high, is not clamped.
	seamAnchorBits = 0x2007ffff

	// seamBlockSize is the excessive block size of the seam chain, which
	// limits a 600-tick block to it and a 60-tick block to a tenth of it.
	seamBlockSize = 2000000

	// seamLargeBlockSize is the size of the largest blocks before the seam,
	// above the limit of a 60-tick block.
	seamLargeBlockSize = 300000

	// upgrade2027Never is an activation time no block reaches.
	upgrade2027Never = 1<<48 - 1
)

// Upgrade2027Seam holds the chain parameters that a chain generated by
// GenerateUpgrade2027Blocks is valid under.  The chain is also built for the
// regression test network with Magnetic Anomaly, Upgrade9 and ABLA inactive,
// CSV active from block 1, and ASERT difficulty adjustment anchored at the
// genesis block.
type Upgrade2027Seam struct {
	// ActivationHeight is the height of the activation block, the last
	// 600-tick block, when the upgrade activates.
	ActivationHeight int32

	// ActivationTime is the upgrade 2027 activation time.  It is 2^48-1
	// when the chain never activates the upgrade.
	ActivationTime uint64

	// AsertAnchorParentTime and AsertAnchorBits are the parent time and
	// bits of the ASERT anchor at height 0.
	AsertAnchorParentTime int64
	AsertAnchorBits       uint32

	// ExcessiveBlockSize is the block size limit of a 600-tick block.
	ExcessiveBlockSize uint32
}

// padSpendTo returns a function that pads the output script of the spending
// transaction so that the block serializes to the passed size.  The output
// script must be a single byte before.
func padSpendTo(size int) func(*wire.MsgBlock) {
	return func(b *wire.MsgBlock) {
		// The script length takes five bytes instead of one.
		pad := size - b.SerializeSize() - 3
		replaceSpendScript(repeatOpcode(0x00, pad))(b)
	}
}

// legacyCoinbase returns a function that sets the version of the coinbase to 1
// and the sequence of its input to the passed one, which is the forbidden
// coinbase shape when the sequence is final and the coinbase pays 25 BCH or
// more.
func legacyCoinbase(sequence uint32) func(*wire.MsgBlock) {
	return func(b *wire.MsgBlock) {
		b.Transactions[0].Version = 1
		b.Transactions[0].TxIn[0].Sequence = sequence
	}
}

// setBits returns a function that sets the bits of the block.
func setBits(bits uint32) func(*wire.MsgBlock) {
	return func(b *wire.MsgBlock) {
		b.Header.Bits = bits
	}
}

// setTimestamp returns a function that sets the timestamp of the block.
func setTimestamp(t time.Time) func(*wire.MsgBlock) {
	return func(b *wire.MsgBlock) {
		b.Header.Timestamp = t
	}
}

// GenerateUpgrade2027Blocks returns tests for the blocks around the upgrade
// 2027 activation block at activationHeight, which must be from 102 to 149,
// or for the same heights of a chain that never activates the upgrade when
// active is false.  The blocks are stamped on their ticks, so that the
// difficulty only changes with the target interval, and the returned seam
// holds the chain parameters they are valid under.
//
// Each rejected block, and each block that is accepted once its lock expires,
// is at the first height where the outcome differs from counting blocks as
// before the upgrade.
func GenerateUpgrade2027Blocks(activationHeight int32, active bool) (tests [][]TestInstance, seam Upgrade2027Seam, err error) {
	// In order to simplify the generation code which really should never
	// fail unless the test code itself is broken, panics are used
	// internally.  This deferred func ensures any panics don't escape the
	// generator by replacing the named error return with the underlying
	// panic error.
	defer func() {
		if r := recover(); r != nil {
			tests = nil

			switch rt := r.(type) {
			case string:
				err = errors.New(rt)
			case error:
				err = rt
			default:
				err = errors.New("unknown panic")
			}
		}
	}()

	// The coinbase of block 1 matures before the activation block, and the
	// regtest subsidy halves after it, at chunk 150, and before height
	// 1251 where version 1 blocks become invalid.
	ha := activationHeight
	if ha < 102 || ha > 149 {
		return nil, seam, fmt.Errorf("activation height %d is not "+
			"from 102 to 149", ha)
	}

	params := *regressionNetParams
	g, err := makeTestGenerator(&params)
	if err != nil {
		return nil, seam, err
	}
	g.tickTimes = true
	g.anchorBits = seamAnchorBits
	genesisTime := params.GenesisBlock.Header.Timestamp.Unix()
	seam = Upgrade2027Seam{
		ActivationHeight:      ha,
		ActivationTime:        upgrade2027Never,
		AsertAnchorParentTime: genesisTime - 600,
		AsertAnchorBits:       seamAnchorBits,
		ExcessiveBlockSize:    seamBlockSize,
	}
	if active {
		// The median time past of a block is the time of the block
		// five before it, so it first reaches this at block ha.
		g.upgrade2027Height = ha
		seam.ActivationTime = uint64(genesisTime + int64(ha-5)*600)
		params.Upgrade2027ActivationTime = seam.ActivationTime
	}

	accept := func(isMainChain bool) {
		tests = append(tests, []TestInstance{AcceptedBlock{g.tipName,
			g.tip, g.tipHeight, isMainChain, false}})
	}
	nextMain := func(spend *spendableOut, mungers ...func(*wire.MsgBlock)) {
		g.nextBlock(fmt.Sprintf("b%d", g.tipHeight+1), spend, mungers...)
		accept(true)
	}
	child := func(name string, spend *spendableOut, mungers ...func(*wire.MsgBlock)) {
		parent := g.tipName
		g.nextBlock(name, spend, mungers...)
		g.setTip(parent)
	}
	rejectChild := func(name string, code blockchain.ErrorCode, spend *spendableOut, mungers ...func(*wire.MsgBlock)) {
		child(name, spend, mungers...)
		block := g.blocksByName[name]
		tests = append(tests, []TestInstance{RejectedBlock{name, block,
			g.blockHeights[name], code}})
	}
	sideChild := func(name string, spend *spendableOut, mungers ...func(*wire.MsgBlock)) {
		child(name, spend, mungers...)
		block := g.blocksByName[name]
		tests = append(tests, []TestInstance{AcceptedBlock{name, block,
			g.blockHeights[name], false, false}})
	}
	coinbaseOut := func(height int32) *spendableOut {
		out := makeSpendableOut(g.blocksByName[fmt.Sprintf("b%d", height)],
			0, 0)
		return &out
	}
	mainTime := func(height int32) time.Time {
		return g.blocksByName[fmt.Sprintf("b%d", height)].Header.Timestamp
	}
	spendTx := func(prevOut wire.OutPoint, amount int64, version int32,
		sequence, lockTime uint32) *wire.MsgTx {

		tx := createSpendTx(&spendableOut{prevOut, bchutil.Amount(amount)}, 0)
		tx.Version = version
		tx.TxIn[0].Sequence = sequence
		tx.LockTime = lockTime
		return tx
	}

	// ---------------------------------------------------------------------
	// Blocks before the seam.
	//
	//   genesis -> b1 -> ... -> b(ha-2)
	// ---------------------------------------------------------------------

	for g.tipHeight < ha-2 {
		nextMain(nil)
	}

	// Fund the lock tests from block ha-1: a relative lock of two units
	// and a lock time of ha+1, both counting 600 ticks a unit.
	//
	//   ... -> b(ha-2) -> b(ha-1)
	fundOut := coinbaseOut(1)
	fund := spendTx(fundOut.prevOut, int64(fundOut.amount), 1,
		wire.MaxTxInSequenceNum, 0)
	fund.TxOut = []*wire.TxOut{
		wire.NewTxOut(10*bchutil.SatoshiPerBitcoin, opTrueScript,
			wire.TokenData{}),
		wire.NewTxOut(10*bchutil.SatoshiPerBitcoin, opTrueScript,
			wire.TokenData{}),
		wire.NewTxOut(int64(fundOut.amount)-
			20*bchutil.SatoshiPerBitcoin, opTrueScript, wire.TokenData{}),
	}
	nextMain(nil, additionalTx(fund))
	fundHash := fund.TxHash()
	csvTx := spendTx(wire.OutPoint{Hash: fundHash, Index: 0},
		10*bchutil.SatoshiPerBitcoin, 2, 2, 0)
	lockTimeTx := spendTx(wire.OutPoint{Hash: fundHash, Index: 1},
		10*bchutil.SatoshiPerBitcoin, 1, wire.MaxTxInSequenceNum-1,
		uint32(ha+1))

	// The activation block is still a 600-tick block: it may have the
	// forbidden coinbase shape, be larger than a 60-tick block may be and
	// spend the coinbase 100 blocks below it.
	//
	//   ... -> b(ha-1) -> b(ha)
	nextMain(coinbaseOut(ha-100), legacyCoinbase(wire.MaxTxInSequenceNum),
		padSpendTo(seamLargeBlockSize))
	g.assertTipBlockSize(seamLargeBlockSize)

	// The minimum difficulty is allowed after more than two 600-tick
	// intervals.
	//
	//   ... -> b(ha-1) -> b(ha)
	//                 \-> bha-mindiff-1200
	//                 \-> bha-mindiff-1201
	g.setTip(fmt.Sprintf("b%d", ha-1))
	rejectChild("bha-mindiff-1200", blockchain.ErrUnexpectedDifficulty,
		nil, setBits(params.PowLimitBits),
		setTimestamp(mainTime(ha-1).Add(1200*time.Second)))
	sideChild("bha-mindiff-1201", nil, setBits(params.PowLimitBits),
		setTimestamp(mainTime(ha-1).Add(1201*time.Second)))
	g.setTip(fmt.Sprintf("b%d", ha))

	if !active {
		// Without the upgrade the block after the activation block
		// keeps every rule of the blocks before it.
		//
		//   ... -> b(ha) -> b(ha+1) -> b(ha+2)
		//                \-> bn-mindiff-121
		//                \-> bn-locktime
		rejectChild("bn-mindiff-121", blockchain.ErrUnexpectedDifficulty,
			nil, setBits(params.PowLimitBits),
			setTimestamp(mainTime(ha).Add(121*time.Second)))
		rejectChild("bn-locktime", blockchain.ErrUnfinalizedTx, nil,
			additionalTx(lockTimeTx))
		nextMain(coinbaseOut(ha-99), legacyCoinbase(wire.MaxTxInSequenceNum),
			additionalTx(csvTx), padSpendTo(seamLargeBlockSize))
		g.assertTipBlockSize(seamLargeBlockSize)
		nextMain(nil, additionalTx(lockTimeTx))
		return tests, seam, nil
	}

	// ---------------------------------------------------------------------
	// The first 60-tick block.
	//
	//   ... -> b(ha) -> b(ha+1)
	//                \-> bs-bits, bs-mindiff-120, bs-subsidy, bs-immature,
	//                    bs-shape, bs-toobig (all rejected)
	//                \-> bs-mindiff-121, bs-v2 (side chain)
	// ---------------------------------------------------------------------

	// The 600-tick bits, the 600-tick subsidy and the coinbase 99 blocks
	// below, 59,460 ticks deep, are rejected.  So is the minimum difficulty
	// after two 60-tick intervals.
	if g.blockBits(ha+1) == seamAnchorBits {
		panic("the 60-tick bits are the 600-tick bits")
	}
	rejectChild("bs-bits", blockchain.ErrUnexpectedDifficulty, nil,
		setBits(seamAnchorBits))
	rejectChild("bs-mindiff-120", blockchain.ErrUnexpectedDifficulty, nil,
		setBits(params.PowLimitBits),
		setTimestamp(mainTime(ha).Add(120*time.Second)))
	legacySubsidy := blockchain.CalcBlockSubsidy(int64(ha+1)*600, 600,
		&params)
	tickSubsidy := blockchain.CalcBlockSubsidy(g.blockTicks(ha+1), 60,
		&params)
	rejectChild("bs-subsidy", blockchain.ErrBadCoinbaseValue, nil,
		additionalCoinbase(bchutil.Amount(legacySubsidy-tickSubsidy)))
	rejectChild("bs-immature", blockchain.ErrImmatureSpend,
		coinbaseOut(ha-99))

	// A coinbase of 25 BCH or more, the subsidy plus a 45 BCH fee, must
	// escape the forbidden shape, here with a non-final sequence.  The
	// block may be a tenth of the 600-tick limit.
	const shapeFee = 45 * bchutil.SatoshiPerBitcoin
	if tickSubsidy+shapeFee < 25*bchutil.SatoshiPerBitcoin {
		panic("the shape test coinbase pays under 25 BCH")
	}
	shapeSpend := coinbaseOut(2)
	feeMungers := []func(*wire.MsgBlock){additionalSpendFee(shapeFee),
		additionalCoinbase(shapeFee)}
	rejectChild("bs-shape", blockchain.ErrBadCoinbaseShape, shapeSpend,
		append(feeMungers, legacyCoinbase(wire.MaxTxInSequenceNum))...)
	rejectChild("bs-toobig", blockchain.ErrBlockTooBig, shapeSpend,
		append(feeMungers, padSpendTo(seamBlockSize/10+1))...)
	nextMain(shapeSpend, append(feeMungers,
		legacyCoinbase(wire.MaxTxInSequenceNum-1),
		padSpendTo(seamBlockSize/10))...)
	g.assertTipBlockSize(seamBlockSize / 10)

	g.setTip(fmt.Sprintf("b%d", ha))
	sideChild("bs-mindiff-121", nil, setBits(params.PowLimitBits),
		setTimestamp(mainTime(ha).Add(121*time.Second)))
	sideChild("bs-v2", shapeSpend, feeMungers...)
	g.setTip(fmt.Sprintf("b%d", ha+1))

	// ---------------------------------------------------------------------
	// Locks released at the tick boundary.
	//
	// The coinbase of block ha-99 matures at ha+10, when it is 59,400 +
	// 600 ticks deep.  The relative lock of 1,200 ticks on the output of
	// block ha-1 expires at ha+10, 600 + 10*60 ticks after it.  The lock
	// time ha+1, 600*(ha+1) ticks, is passed at ha+11.
	//
	//   ... -> b(ha+8) -> b(ha+9) -> b(ha+10) -> b(ha+11)
	//                 \-> bs9-immature, bs9-csv
	//                              \-> bs10-locktime
	// ---------------------------------------------------------------------

	for g.tipHeight < ha+8 {
		nextMain(nil)
	}
	rejectChild("bs9-immature", blockchain.ErrImmatureSpend,
		coinbaseOut(ha-99))
	rejectChild("bs9-csv", blockchain.ErrUnfinalizedTx, nil,
		additionalTx(csvTx))
	nextMain(nil)
	rejectChild("bs10-locktime", blockchain.ErrUnfinalizedTx, nil,
		additionalTx(lockTimeTx))
	nextMain(coinbaseOut(ha-99), additionalTx(csvTx))
	nextMain(nil, additionalTx(lockTimeTx))

	// ---------------------------------------------------------------------
	// The subsidy halves at chunk 150, the 600-tick chunk of the block's
	// ticks, which is reached at ha+(149-ha)*10+1.
	// ---------------------------------------------------------------------

	halving := ha + (149-ha)*10 + 1
	for g.tipHeight < halving-1 {
		nextMain(nil)
	}
	before := blockchain.CalcBlockSubsidy(g.blockTicks(halving-1), 60,
		&params)
	after := blockchain.CalcBlockSubsidy(g.blockTicks(halving), 60, &params)
	if before != 5*bchutil.SatoshiPerBitcoin ||
		after != 25*bchutil.SatoshiPerBitcoin/10 {

		panic(fmt.Sprintf("subsidies %d and %d at %d are not 5 and "+
			"2.5 BCH", before, after, halving))
	}
	rejectChild("bs-halving", blockchain.ErrBadCoinbaseValue, nil,
		additionalCoinbase(bchutil.Amount(before-after)))
	nextMain(nil)

	// ---------------------------------------------------------------------
	// Coinbase maturity of 60,000 ticks: the coinbase of block ha-1 is
	// mature at ha+990, and that of block ha+1 at ha+1001.
	// ---------------------------------------------------------------------

	for _, m := range []struct {
		coinbase, mature int32
	}{{ha - 1, ha + 990}, {ha + 1, ha + 1001}} {
		for g.tipHeight < m.mature-2 {
			nextMain(nil)
		}
		rejectChild(fmt.Sprintf("bs-immature-%d", m.coinbase),
			blockchain.ErrImmatureSpend, coinbaseOut(m.coinbase))
		nextMain(nil)
		nextMain(coinbaseOut(m.coinbase))
	}

	return tests, seam, nil
}
